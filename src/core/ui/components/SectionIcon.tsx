/** A pole's or a module's tile: its colour, its icon. The same everywhere, so it's recognised at a glance. */
export function SectionTile({ id, size = 48 }: { id: SectionId | PoleId; size?: number }) {
  const s = POLES.find((p) => p.id === id) ?? CLUB_SECTIONS.find((m) => m.id === id)!;
  return (
    <span className="grid shrink-0 place-items-center" style={{ width: size, height: size, borderRadius: Math.round(size * 0.31), background: s.color, color: s.ink }} aria-hidden="true">
      <Glyph name={id} size={Math.round(size * 0.5)} />
    </span>
  );
}
