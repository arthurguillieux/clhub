/**
 * An idea not already used in this game, or any idea once they've all been used.
 * `random` is injectable for the tests.
 */
export function pickMissionIdea(used: Iterable<string>, random: () => number = Math.random): string {
  const taken = new Set(Array.from(used, (m) => m.trim()));
  const free = MISSION_IDEAS.filter((idea) => !taken.has(idea));
  const pool = free.length ? free : MISSION_IDEAS;
  return pool[Math.floor(random() * pool.length)]!;
}

/** True when the text is one of the ideas, untouched — so offering another one won't erase anything typed. */
export const isMissionIdea = (text: string) => MISSION_IDEAS.includes(text.trim());
